        <legend>SkyGuard Help</legend>
        <div class="p-2">
            SkyGuard blacks out moving-head light output while any aircraft is inside a radius you set.
            It forces only each head's dimmer and shutter channels; pan, tilt, color and everything else keep following the sequence.
            If aircraft data stops arriving during a show, the heads stay dark until it returns.
            Its log is <code>plugin-fpp-plugin-SkyGuard.log</code>, under Logs in the File Manager.
        </div>
